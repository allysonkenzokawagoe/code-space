CREATE SEQUENCE IF NOT EXISTS public.SEQ_USUARIO START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS public.SEQ_USUARIO_HIST START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS public.SEQ_ROLE START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS public.SEQ_CARGO START WITH 1 INCREMENT BY 1;

CREATE TABLE ROLE(
    ID INTEGER NOT NULL,
    NOME VARCHAR(255) NOT NULL,
    DESCRICAO VARCHAR(255) NOT NULL,
    SITUACAO VARCHAR(255) NOT NULL,
    CONSTRAINT PK_ROLE PRIMARY KEY (ID)
);

CREATE TABLE CARGO(
    ID INT NOT NULL,
    NOME VARCHAR(255) NOT NULL,
    DESCRICAO VARCHAR(255) NOT NULL,
    SITUACAO VARCHAR(255) NOT NULL,
    CONSTRAINT PK_CARGO PRIMARY KEY (ID)
);

CREATE TABLE CARGO_ROLE(
    FK_CARGO INTEGER NOT NULL,
    FK_ROLE INTEGER NOT NULL,
    CONSTRAINT PK_CARGO_ROLE PRIMARY KEY (FK_ROLE, FK_CARGO),
    FOREIGN KEY (FK_CARGO) REFERENCES CARGO(ID),
    FOREIGN KEY (FK_ROLE) REFERENCES ROLE(ID)
);

CREATE TABLE USUARIO(
    ID    INTEGER NOT NULL,
    NOME  VARCHAR(255),
    EMAIL VARCHAR(255),
    SENHA VARCHAR(255),
    SITUACAO VARCHAR(255),
    FK_CARGO INTEGER NOT NULL,
    CONSTRAINT pk_usuario PRIMARY KEY (id),
    FOREIGN KEY (FK_CARGO) REFERENCES CARGO(ID)
);

CREATE TABLE USUARIO_HIST(
    ID    INTEGER NOT NULL,
    DATA_ALTERACAO TIMESTAMP NOT NULL,
    TIPO_ALTERACAO VARCHAR(20),
    FK_USUARIO INTEGER NOT NULL,
    FOREIGN KEY (FK_USUARIO) REFERENCES USUARIO(ID)
);
